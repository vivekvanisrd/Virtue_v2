  const parsedMap = new Map<string, ParsedStudent>();

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (line.includes("Student Name") && line.includes("Parent Name")) continue;
    if (line.startsWith("can u check")) continue;

    const parts = line.split("\t").map(p => p.trim());
    if (parts.length < 2) continue;

    let admNo = parts[0] || "";
    let studentName = parts[1] || "";
    let parentName = parts[2] || "";
    let phoneStr = parts[3] || "";
    let className = parts[5] || "";

    let admFee = parseNum(parts[7]);
    let concession = parseNum(parts[8]);
    let tuition = parseNum(parts[9]);
    let transport = parseNum(parts[10]);
    let totalDue = parseNum(parts[12]);

    if (!studentName || studentName.toUpperCase() === "STUDENT NAME" || studentName === "0") continue;

    const nameParts = studentName.split(" ");
    const firstName = nameParts[0];
    const lastName = nameParts.slice(1).join(" ");

    const key = admNo ? admNo.toUpperCase() : `${studentName.toUpperCase()}_${cleanPhone(phoneStr) || "NOPHONE"}`;

    if (!parsedMap.has(key)) {
      parsedMap.set(key, {
        admNo: admNo.toUpperCase(),
        studentName: studentName.toUpperCase(),
        firstName,
        lastName,
        parentName: parentName.toUpperCase(),
        phone: cleanPhone(phoneStr),
        className: className.toUpperCase(),
        admissionFee: admFee,
        concession,
        tuitionFee: tuition,
        transportFee: transport,
        totalDue
      });
    }
  }

