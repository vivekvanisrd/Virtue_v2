async function main() {
  const lines = RAW_PAYMENTS_TEXT.split(/\r?\n/).filter(l => l.trim().length > 0);

  const parsedPayments: any[] = [];
  for (let i = 1; i < lines.length; i++) {
    const parts = lines[i].split("\t").map(p => p.trim());
    if (parts.length >= 8) {
      const slNo = parseInt(parts[0]) || i;
      const dateStr = parts[1];
      const receiptNo = parts[2];
      const admNo = parts[3];
      const studentName = parts[4];
      const cash = parseFloat(parts[5]) || 0;
      const online = parseFloat(parts[6]) || 0;
      const total = parseFloat(parts[7]) || (cash + online);
      const paymentFor = parts[8] || "";
      const feeHead = parts[9] || "Tuition";
      const collectedBy = parts[10] || "";
      const utrRef = parts[11] || "";

      const normHead = feeHead.includes("Tuition") ? "Tuition" : feeHead.includes("Transport") ? "Transport" : feeHead.includes("Admission") ? "Admission" : "Other";

      parsedPayments.push({ slNo, dateStr, receiptNo, admNo, studentName, cash, online, total, paymentFor, feeHead: normHead, collectedBy, utrRef });
    }
  }

  const dbStudents = await prisma.student.findMany({
    where: { branchId: BRANCH_ID },
    select: {
      id: true,
      admissionNumber: true,
      firstName: true,
      lastName: true,
      financial: {
        select: {
          id: true,
          netTuition: true,
          transportFee: true,
          admissionFee: true
        }
      }
    }
  });

  const studentPaymentsMap = new Map<string, {
    student: any;
    tuitionPaid: number;
    transportPaid: number;
    admissionPaid: number;
    receipts: any[];
  }>();

  for (const p of parsedPayments) {
    const admKey = (p.admNo || "").trim().toUpperCase();
    const pNameNorm = (p.studentName || "").replace(/[^A-Z0-9]/gi, "").toUpperCase();

    let match = dbStudents.find(s => (s.admissionNumber || "").trim().toUpperCase() === admKey);
    if (!match && pNameNorm) {
      match = dbStudents.find(s => {
        const dbNameNorm = `${s.firstName || ""}${s.lastName || ""}`.replace(/[^A-Z0-9]/gi, "").toUpperCase();
        return dbNameNorm === pNameNorm || dbNameNorm.includes(pNameNorm) || pNameNorm.includes(dbNameNorm);
      });
    }

    if (match) {
      if (!studentPaymentsMap.has(match.id)) {
        studentPaymentsMap.set(match.id, { student: match, tuitionPaid: 0, transportPaid: 0, admissionPaid: 0, receipts: [] });
      }
      const item = studentPaymentsMap.get(match.id)!;
      if (p.feeHead === "Tuition") item.tuitionPaid += p.total;
      else if (p.feeHead === "Transport") item.transportPaid += p.total;
      else if (p.feeHead === "Admission") item.admissionPaid += p.total;
      item.receipts.push(p);
    }
  }

  console.log("=== REMAINING 6 SURPLUS STUDENTS (TUITION SURPLUS ONLY) ===");
  for (const [sId, data] of studentPaymentsMap.entries()) {
    const s = data.student;
    const fin = s.financial;
    let netTuition = Number(fin?.netTuition || 0);

    if (data.tuitionPaid > netTuition && netTuition > 0) {
      console.log(`\nStudent: ${s.firstName} ${s.lastName || ""} (Adm: ${s.admissionNumber})`);
      console.log(`  Assigned Net Tuition: ₹${netTuition.toLocaleString('en-IN')}`);
      console.log(`  Total Tuition Paid: ₹${data.tuitionPaid.toLocaleString('en-IN')}`);
      console.log(`  Tuition Surplus: ₹${(data.tuitionPaid - netTuition).toLocaleString('en-IN')}`);
      for (const r of data.receipts) {
        console.log(`    - Receipt #${r.receiptNo} (${r.dateStr}): ₹${r.total} [${r.feeHead}] (${r.paymentFor})`);
      }
    }
  }
}

main().catch(console.error).finally(() => prisma.$disconnect());
